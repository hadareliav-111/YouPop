import type { Friendship } from "../types";
import { supabase } from "./supabaseClient";

const TABLE = "friendships";

interface FriendshipRow {
  id: string;
  requester_id: string;
  addressee_id: string;
  status: Friendship["status"];
  created_at: string;
  responded_at: string | null;
}

function fromRow(row: FriendshipRow): Friendship {
  return {
    id: row.id,
    requesterId: row.requester_id,
    addresseeId: row.addressee_id,
    status: row.status,
    createdAt: row.created_at,
    respondedAt: row.responded_at,
  };
}

export interface FoundUser {
  id: string;
  username: string;
}

// The only way to discover another user's id — an exact (case-insensitive)
// username match via a security-definer RPC, never a listing/browse query.
export async function findUserByUsername(username: string): Promise<FoundUser | null> {
  const { data, error } = await supabase.rpc("find_user_by_username", {
    search_username: username,
  });
  if (error) throw error;
  const rows = data as FoundUser[] | null;
  return rows && rows.length > 0 ? rows[0] : null;
}

// Every friendship/request row involving the current user — the select
// policy already scopes this, so no extra filtering is needed here.
export async function fetchMyFriendships(userId: string): Promise<Friendship[]> {
  const { data, error } = await supabase
    .from(TABLE)
    .select("*")
    .or(`requester_id.eq.${userId},addressee_id.eq.${userId}`);
  if (error) throw error;
  return (data as FriendshipRow[]).map(fromRow);
}

export interface ProfileSummary {
  id: string;
  username: string;
  displayName: string;
}

// Resolves counterpart usernames for existing friendships/requests. Relies
// on the profiles RLS policy that only reveals a profile to someone who
// already has a friendships row with them — a stranger's profile is never
// visible, regardless of what ids are passed here.
export async function fetchProfiles(ids: string[]): Promise<ProfileSummary[]> {
  if (ids.length === 0) return [];
  const { data, error } = await supabase
    .from("profiles")
    .select("id, username, display_name")
    .in("id", ids);
  if (error) throw error;
  return (data as { id: string; username: string; display_name: string }[]).map((row) => ({
    id: row.id,
    username: row.username,
    displayName: row.display_name,
  }));
}

// `id` is generated by the caller (same convention as WatchlistItem/
// Recommendation) so the sender can optimistically show the new pending
// request immediately, with the same id the row will actually have.
export async function sendRequest(id: string, myId: string, targetId: string): Promise<void> {
  const { error } = await supabase.from(TABLE).insert({
    id,
    requester_id: myId,
    addressee_id: targetId,
    status: "pending",
  });
  if (error) throw error;
}

// The only path to status='accepted' — see accept_friend_request() in
// supabase/schema.sql for why this has to be an RPC rather than a raw
// update.
export async function acceptRequest(requestId: string): Promise<void> {
  const { error } = await supabase.rpc("accept_friend_request", {
    request_id: requestId,
  });
  if (error) throw error;
}

// Used for cancel, decline, and Remove Friend alike — all three are just
// "delete a row I'm part of" (see the single delete policy in
// supabase/schema.sql), so one function covers all three call sites.
export async function deleteFriendship(requestId: string): Promise<void> {
  const { error } = await supabase.from(TABLE).delete().eq("id", requestId);
  if (error) throw error;
}
